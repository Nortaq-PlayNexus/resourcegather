def mk(name, url):
    return {"name": name, "url": url}


def run():
    # Paste
    d = load("data/paste_sites.json")
    sites = list(d.get("sites", []))
    for n, u in PASTE:
        sites.append(mk(n, u))
    d["sites"] = dedupe(sites)
    save("data/paste_sites.json", d)
    print("paste_sites.json: %d entries" % len(d["sites"]))

    # Torrent
    d = load("data/torrent_sites.json")
    pub = list(d.get("public", []))
    legal = list(d.get("legal", []))
    priv = list(d.get("private_trackers", []))
    for n, u in TORRENT_PUBLIC:
        pub.append(mk(n, u))
    for n, u in TORRENT_LEGAL:
        legal.append(mk(n, u))
    for n, u in TORRENT_PRIVATE:
        priv.append(mk(n, u))
    d["public"] = dedupe(pub)
    d["legal"] = dedupe(legal)
    d["private_trackers"] = dedupe(priv)
    save("data/torrent_sites.json", d)
    print("torrent_sites.json: %d entries" % (len(d["public"]) + len(d["legal"]) + len(d["private_trackers"])))

    # Inbetween
    d = load("data/inbetween.json")
    for key, items in [
        ("ransomware_leak_sites", RANSOMWARE_LEAK),
        ("cybercrime_forums", FORUMS),
        ("darkweb_search", DARKWEB_SEARCH),
        ("i2p", I2P),
        ("aggregators", AGGREGATORS),
        ("stealer_logs", STEALER_LOGS),
        ("telegram_osint", TELEGRAM),
        ("frameworks", FRAMEWORKS),
    ]:
        cur = list(d.get(key, []))
        for n, u in items:
            cur.append(mk(n, u))
        d[key] = dedupe(cur)
    save("data/inbetween.json", d)
    tot = sum(len(d.get(k, [])) for k in d)
    print("inbetween.json: %d entries" % tot)

    # Search targets
    d = load("data/search_targets.json")
    cur = list(d.get("targets", []))
    for n, u in SEARCH_TARGETS:
        cur.append({"name": n, "search_url": u, "network": "clear"})
    d["targets"] = dedupe(cur, key="search_url")
    save("data/search_targets.json", d)
    print("search_targets.json: %d entries" % len(d["targets"]))


if __name__ == "__main__":
    run()
