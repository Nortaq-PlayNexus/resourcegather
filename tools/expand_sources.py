"""tools/expand_sources.py

Expands the data/*.json inventories with 500+ additional, categorized sources.
- Real, well-known clearnet services (paste/torrent/OSINT/threat-intel).
- .onion / .i2p entries use "[FILL]" placeholders (skipped by the runtime
  generator) because live hidden-service addresses change frequently and must
  be verified by the operator.

Run:  python tools/expand_sources.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(p):
    fp = os.path.join(ROOT, p)
    if os.path.exists(fp):
        with open(fp, "r", encoding="utf-8") as fh:
            return json.load(fh)
    return {}


def save(p, d):
    fp = os.path.join(ROOT, p)
    os.makedirs(os.path.dirname(fp), exist_ok=True)
    with open(fp, "w", encoding="utf-8") as fh:
        json.dump(d, fh, indent=2)


def dedupe(items, key="url"):
    seen, out = set(), []
    for it in items:
        k = (it.get(key) or "").lower()
        if k in seen or not it.get("name"):
            continue
        seen.add(k)
        out.append(it)
    return out


